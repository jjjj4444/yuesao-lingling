  if (hasAny(name, ['水果', '坚果', '芝麻糊', '酸奶', '蛋挞', '西多士', '松饼', '欧包', '酥', '糕', '派', '贝果', '饼干', '布丁', '蜜豆', '蓝莓'])) return '点心'
